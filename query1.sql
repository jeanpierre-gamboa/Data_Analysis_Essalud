USE BD_ESSALUD;

CREATE TABLE HORAS_CONSULTA_EXTERNA(
	PERIODO INT NOT NULL,
	DEPARTAMENTO NVARCHAR(100) NOT NULL,
	PROVINCIA NVARCHAR(100) NOT NULL,
	DISTRITO NVARCHAR (100) NOT NULL,
	UBIGEO INT NOT NULL,
	SES_DESRED NVARCHAR(100) NOT NULL,
	SES_DESCAS NVARCHAR(100) NOT NULL,
	CANTIDAD INT NOT NULL,
	DES_SER NVARCHAR (100) NOT NULL,
	DES_ACT NVARCHAR(100) NOT NULL
);
GO

TRUNCATE TABLE dbo.HORAS_CONSULTA_EXTERNA;

BULK INSERT dbo.HORAS_CONSULTA_EXTERNA
FROM 'C:\data_essalud\horas_consulta_externa.csv'
WITH (
    FIRSTROW = 2,
    FIELDTERMINATOR = ',',
    ROWTERMINATOR = '0x0d0a',
    CODEPAGE = '65001',
    TABLOCK
);

SELECT DES_ACT, SUM(CANTIDAD) as Suma_Total
FROM dbo.HORAS_CONSULTA_EXTERNA
GROUP BY DES_ACT;

SELECT 
	DES_SER,
	SUM(CASE WHEN DES_ACT = 'Horas Prog.' 
	THEN CANTIDAD ELSE 0 END) AS horas_prog,
	SUM(CASE WHEN DES_ACT = 'Hras.Efec.(Eje)' 
	THEN CANTIDAD ELSE 0 END) AS horas_efec
FROM dbo.HORAS_CONSULTA_EXTERNA
GROUP BY DES_SER;


